// Writes src/api/schema.gen.ts from the server's OpenAPI document, taken from the compatibility baseline that
// `go test` keeps equal to what the server generates (ADR-0082). Run: npm run gen:api
// It covers the schema keywords the server emits and throws on any other, so nothing is silently typed wrong.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SNAPSHOTS = new URL("../../server/internal/apicompat/snapshots/", import.meta.url);
export const OUTPUT = fileURLToPath(new URL("../src/api/schema.gen.ts", import.meta.url));

// Keywords that shape the type, and keywords that only limit values or document them.
const SHAPE = ["$ref", "type", "enum", "const", "anyOf", "oneOf", "allOf", "properties", "required", "additionalProperties", "items"];
const IGNORED = ["format", "pattern", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf", "minLength", "maxLength", "minItems", "maxItems", "uniqueItems", "minProperties", "maxProperties", "description", "title", "default", "examples", "example", "readOnly", "writeOnly", "deprecated", "contentEncoding", "contentMediaType"];

const key = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name));
const union = (parts) => [...new Set(parts)].join(" | ");

function typeOf(schema, indent, where) {
  if (schema === true) return "unknown";
  for (const k of Object.keys(schema)) {
    if (!SHAPE.includes(k) && !IGNORED.includes(k) && !k.startsWith("x-")) throw new Error(`${where}: unsupported schema keyword ${k}`);
  }
  if (schema.$ref) return schema.$ref.split("/").pop();
  const types = [schema.type].flat().filter(Boolean);
  const nullable = types.includes("null");
  const orNull = (t) => (nullable ? union([t, "null"]) : t);
  if ("const" in schema) return orNull(JSON.stringify(schema.const));
  if (schema.enum) return orNull(union(schema.enum.map((v) => JSON.stringify(v))));
  for (const [k, join] of [["anyOf", " | "], ["oneOf", " | "], ["allOf", " & "]]) {
    // A branch that only lists required names narrows validation without changing the shape.
    const branches = schema[k]?.filter((b) => Object.keys(b).some((n) => n !== "required"));
    if (branches?.length) return orNull(branches.map((b, i) => `(${typeOf(b, indent, `${where}.${k}[${i}]`)})`).join(join));
  }
  const parts = types.filter((t) => t !== "null").map((t) => {
    if (t === "string" || t === "boolean") return t;
    if (t === "integer" || t === "number") return "number";
    if (t === "array") {
      const item = typeOf(schema.items ?? true, indent, `${where}[]`);
      return /[|&]/.test(item) && !item.startsWith("{") ? `(${item})[]` : `${item}[]`;
    }
    if (t === "object") return objectOf(schema, indent, where);
    throw new Error(`${where}: unsupported type ${t}`);
  });
  if (!types.length) return schema.properties ? objectOf(schema, indent, where) : "unknown";
  return orNull(parts.length ? union(parts) : "null");
}

function objectOf(schema, indent, where) {
  const props = Object.entries(schema.properties ?? {});
  const extra = schema.additionalProperties;
  if (!props.length) {
    if (extra === false) return "Record<string, never>";
    return `Record<string, ${typeof extra === "object" ? typeOf(extra, indent, `${where}.*`) : "unknown"}>`;
  }
  const required = new Set(schema.required ?? []);
  const inner = `${indent}  `;
  const lines = props.filter(([name]) => name !== "$schema").map(([name, sub]) =>
    `${inner}${key(name)}${required.has(name) ? "" : "?"}: ${typeOf(sub, inner, `${where}.${name}`)};`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}

export function generate() {
  // While the API is in development the baseline is the current document. After the first release it is the newest
  // released snapshot in the ledger.
  const ledger = JSON.parse(readFileSync(new URL("ledger.json", SNAPSHOTS), "utf8"));
  const latest = ledger.releases?.at(-1)?.version;
  const source = latest ? `history/${latest}.openapi.json` : "baseline.openapi.json";
  const doc = JSON.parse(readFileSync(new URL(source, SNAPSHOTS), "utf8"));
  const out = [
    "// Generated by scripts/generate-api-types.mjs from the server's OpenAPI document. Do not edit.",
    "// Run `npm run gen:api` after changing the API.",
    "",
  ];
  for (const name of Object.keys(doc.components.schemas).sort()) {
    out.push(`export type ${name} = ${typeOf(doc.components.schemas[name], "", name)};`, "");
  }
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUTPUT, generate());

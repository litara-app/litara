#!/usr/bin/env python3
"""Merge test-results/format-matrix/*.json (written by apps/web/e2e/format.spec.ts)
into research/t005/format-matrix.md. Usage: python scripts/web/format_matrix.py"""
import glob, json, os

root = os.path.join(os.path.dirname(__file__), "..", "..")
src = os.path.join(root, "apps", "web", "test-results", "format-matrix")
rows, browsers = {}, []
for f in sorted(glob.glob(os.path.join(src, "*.json"))):
    kind, browser = os.path.basename(f)[:-5].split("-", 1)
    if browser not in browsers:
        browsers.append(browser)
    for r in json.load(open(f, encoding="utf8")):
        rows.setdefault((kind, r["fixture"]), {})[browser] = r
out = ["# T005 format corpus matrix (observed)", "",
       "Generated by `apps/web/e2e/format.spec.ts` against the real stack (`scripts/web/e2e.sh`) with fixtures from `scripts/web/generate_format_corpus.py`. "
       "Cells are what the browser actually did; nothing is inferred. Fixtures are tiny synthetic files, so a pass is recognition and basic rendering/playback, not a claim about real-world files, DRM, large books, fonts or every codec profile.", ""]
for kind, title in (("ebooks", "Ebooks and comics"), ("audio", "Audio")):
    out += [f"## {title}", "", "| Fixture | " + " | ".join(browsers) + " |", "| --- |" + " --- |" * len(browsers)]
    for (k, fixture), per in rows.items():
        if k != kind:
            continue
        cells = []
        for b in browsers:
            r = per.get(b)
            cells.append("-" if not r else f"{r['outcome']}" + (f": {r['detail'][:90].replace('|', '/')}" if r["detail"] else ""))
        out.append(f"| {fixture} | " + " | ".join(cells) + " |")
    out.append("")
open(os.path.join(root, "research", "t005", "format-matrix.md"), "w", encoding="utf8").write("\n".join(out))
print("wrote research/t005/format-matrix.md", len(rows), "rows")
